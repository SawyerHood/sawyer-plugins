#!/usr/bin/env node
// Vendors bb's built-in sidebar (plugins/thread-list) into plugins/sawyer-sidebar.
//
// bb's sidebar imports internal workspace packages (@bb/client-core,
// @bb/domain, @bb/shared-ui, ...) through barrels that reach most of the app.
// This script follows every @bb/* import symbol by symbol to the file that
// declares it, copies only that closure into vendor/<package>/ (keeping each
// package's src/ layout), and rewrites the imports to relative paths. The
// shared-ui Icon becomes a thin wrapper over the SDK's experimental_Icon, which
// is the same host icon registry the built-in plugin reaches through a build
// shim.
//
// Local changes to upstream files live in patches/sawyer.patch, applied after
// every vendor run. New feature code lives in files the script never touches.
//
// Usage (the bb checkout must have `pnpm install` done):
//   node scripts/vendor-bb-sidebar.mjs --bb <bb-checkout>
//       Re-vendor from the checkout's current HEAD, then apply the patch.
//   node scripts/vendor-bb-sidebar.mjs --bb <bb-checkout> --save-patch
//       Regenerate patches/sawyer.patch from edits made to upstream files.
//       The checkout must be at the revision recorded in vendor/MANIFEST.json.

import { execFileSync } from "node:child_process";
import {
  existsSync,
  mkdirSync,
  mkdtempSync,
  readdirSync,
  readFileSync,
  rmSync,
  statSync,
  writeFileSync,
} from "node:fs";
import { createRequire } from "node:module";
import { tmpdir } from "node:os";
import { dirname, join, relative, resolve, sep } from "node:path";
import { fileURLToPath } from "node:url";
import { parseArgs } from "node:util";

const REPO_ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const OUT = join(REPO_ROOT, "plugins/sawyer-sidebar");
const PATCH_FILE = join(OUT, "patches/sawyer.patch");
const MANIFEST_FILE = join(OUT, "vendor/MANIFEST.json");

/** Upstream plugin files the clone owns itself instead of copying. */
const EXCLUDED_UPSTREAM = [
  /^package\.json$/,
  /^tsconfig\.json$/,
  /^vitest\.config\.ts$/,
  /^PLUGIN_OVERVIEW\.md$/,
  /^skills\//,
];

const ICON_SHIM = `// Generated by scripts/vendor-bb-sidebar.mjs. bb's shared-ui Icon draws from
// the host icon registry; the SDK exposes that same registry to plugins.
import {
  experimental_Icon,
  type ExperimentalIconProps,
} from "@get-bb/plugin-sdk/app";

export type IconName = string;
export type IconProps = ExperimentalIconProps;
export const Icon = experimental_Icon;
`;

const { values: args } = parseArgs({
  options: {
    bb: { type: "string" },
    "save-patch": { type: "boolean", default: false },
  },
});
if (!args.bb) {
  console.error("usage: vendor-bb-sidebar.mjs --bb <bb-checkout> [--save-patch]");
  process.exit(1);
}
const BB = resolve(args.bb);
const PLUGIN = join(BB, "plugins/thread-list");
const PKGS = join(BB, "packages");
const ICON_FILE = join(PKGS, "shared-ui/src/components/ui/icon.tsx");
const require = createRequire(join(BB, "package.json"));
const ts = require("typescript");

const git = (cwd, ...argv) =>
  execFileSync("git", argv, { cwd, encoding: "utf8" }).trim();

function walk(dir, root = dir) {
  return readdirSync(dir).flatMap((name) => {
    const path = join(dir, name);
    if (name === "node_modules" || name.startsWith(".")) return [];
    if (statSync(path).isDirectory()) return walk(path, root);
    return [relative(root, path)];
  });
}

/** Where a source file lands in the clone. */
function outPathFor(file) {
  if (file.startsWith(PLUGIN + sep)) return relative(PLUGIN, file);
  const [pkg, src, ...rest] = relative(PKGS, file).split(sep);
  if (src !== "src") throw new Error(`cannot vendor ${file}: not under src/`);
  return join("vendor", pkg, ...rest);
}

function relativeSpecifier(fromOut, toOut) {
  let spec = relative(dirname(fromOut), toOut)
    .split(sep)
    .join("/")
    .replace(/\.tsx?$/, ".js");
  if (!spec.startsWith(".")) spec = `./${spec}`;
  return spec;
}

function formatStatement(keyword, typeOnly, elements, spec) {
  const head = `${keyword} ${typeOnly ? "type " : ""}`;
  const oneLine = `${head}{ ${elements.join(", ")} } from "${spec}";`;
  if (oneLine.length <= 80) return oneLine;
  return `${head}{\n${elements.map((e) => `  ${e},`).join("\n")}\n} from "${spec}";`;
}

/**
 * Vendor the sidebar into `outDir`. Returns the upstream file list (relative
 * to outDir) and the external packages the vendored code imports.
 */
function vendorInto(outDir) {
  const pluginFiles = walk(PLUGIN).filter(
    (file) => !EXCLUDED_UPSTREAM.some((pattern) => pattern.test(file)),
  );
  const tsRoots = pluginFiles
    .filter((file) => /\.tsx?$/.test(file))
    .map((file) => join(PLUGIN, file));
  const config = ts.getParsedCommandLineOfConfigFile(
    join(PLUGIN, "tsconfig.json"),
    {},
    { ...ts.sys, onUnRecoverableConfigFileDiagnostic() {} },
  );
  const program = ts.createProgram(tsRoots, config.options);
  const checker = program.getTypeChecker();

  const written = new Set();
  const externals = new Set();
  const queue = [...tsRoots];
  const queued = new Set(queue);
  const enqueue = (file) => {
    if (file === ICON_FILE || queued.has(file)) return;
    queued.add(file);
    queue.push(file);
  };
  const write = (outRel, contents) => {
    const target = join(outDir, outRel);
    mkdirSync(dirname(target), { recursive: true });
    writeFileSync(target, contents);
    written.add(outRel.split(sep).join("/"));
  };

  for (const file of pluginFiles.filter((file) => !/\.tsx?$/.test(file))) {
    write(file, readFileSync(join(PLUGIN, file)));
  }
  write(outPathFor(ICON_FILE), ICON_SHIM);

  while (queue.length > 0) {
    const file = queue.shift();
    const source = program.getSourceFile(file);
    if (!source) throw new Error(`${file} is not in the TypeScript program`);
    const fileOut = outPathFor(file);
    const edits = [];

    for (const statement of source.statements) {
      const isImport = ts.isImportDeclaration(statement);
      if (!isImport && !ts.isExportDeclaration(statement)) continue;
      if (!statement.moduleSpecifier) continue;
      const spec = statement.moduleSpecifier.text;

      if (spec.startsWith(".")) {
        const resolved = ts.resolveModuleName(spec, file, config.options, ts.sys)
          .resolvedModule?.resolvedFileName;
        if (!resolved) throw new Error(`cannot resolve ${spec} from ${file}`);
        if (!resolved.includes(`${sep}node_modules${sep}`)) enqueue(resolved);
        continue;
      }
      if (!spec.startsWith("@bb/")) {
        const parts = spec.split("/");
        externals.add(spec.startsWith("@") ? parts.slice(0, 2).join("/") : parts[0]);
        continue;
      }

      // Re-point each named binding at the file that declares it.
      const where = `${spec} in ${relative(BB, file)}`;
      let elements;
      let typeOnly = false;
      if (isImport) {
        const clause = statement.importClause;
        if (!clause || clause.name || !ts.isNamedImports(clause.namedBindings)) {
          throw new Error(`only named imports are supported: ${where}`);
        }
        typeOnly = clause.isTypeOnly;
        elements = clause.namedBindings.elements;
      } else {
        if (!statement.exportClause || !ts.isNamedExports(statement.exportClause)) {
          throw new Error(`export * is not supported: ${where}`);
        }
        typeOnly = statement.isTypeOnly;
        elements = statement.exportClause.elements;
      }

      const byTarget = new Map();
      for (const element of elements) {
        let symbol = checker.getSymbolAtLocation(element.propertyName ?? element.name);
        if (symbol && symbol.flags & ts.SymbolFlags.Alias) {
          symbol = checker.getAliasedSymbol(symbol);
        }
        const declaration = symbol?.declarations?.[0];
        if (!declaration) {
          throw new Error(`cannot resolve ${element.name.text} from ${where}`);
        }
        const declFile = declaration.getSourceFile().fileName;
        if (!declFile.startsWith(PKGS + sep) || declFile.includes(`${sep}node_modules${sep}`)) {
          throw new Error(`${element.name.text} from ${where} is declared outside bb packages (${declFile})`);
        }
        if (symbol.name === "default") {
          throw new Error(`default exports are not supported: ${where}`);
        }
        enqueue(declFile);
        const local = element.name.text;
        const prefix = element.isTypeOnly ? "type " : "";
        const text = symbol.name === local ? `${prefix}${local}` : `${prefix}${symbol.name} as ${local}`;
        const target = relativeSpecifier(fileOut, outPathFor(declFile));
        byTarget.set(target, [...(byTarget.get(target) ?? []), text]);
      }
      const replacement = [...byTarget]
        .sort(([a], [b]) => a.localeCompare(b))
        .map(([target, names]) =>
          formatStatement(isImport ? "import" : "export", typeOnly, names, target),
        )
        .join("\n");
      edits.push({ start: statement.getStart(source), end: statement.end, replacement });
    }

    // Tests mock barrels with vi.mock("@bb/pkg", (importOriginal) => ...).
    // Point the mock (and any import("@bb/pkg") type inside it) at the one
    // file that declares the symbols the factory overrides.
    const visit = (node) => {
      if (
        ts.isCallExpression(node) &&
        /^vi\.(do)?[mM]ock$/.test(node.expression.getText(source)) &&
        ts.isStringLiteral(node.arguments[0]) &&
        node.arguments[0].text.startsWith("@bb/")
      ) {
        const spec = node.arguments[0].text;
        const barrel = ts.resolveModuleName(spec, file, config.options, ts.sys)
          .resolvedModule?.resolvedFileName;
        const moduleSymbol = checker.getSymbolAtLocation(program.getSourceFile(barrel));
        const factory = node.arguments[1]?.getText(source) ?? "";
        const declFiles = new Set();
        for (const exported of checker.getExportsOfModule(moduleSymbol)) {
          if (!new RegExp(`\\b${exported.name}\\b`).test(factory)) continue;
          const resolved = exported.flags & ts.SymbolFlags.Alias
            ? checker.getAliasedSymbol(exported)
            : exported;
          declFiles.add(resolved.declarations[0].getSourceFile().fileName);
        }
        if (declFiles.size !== 1) {
          throw new Error(`vi.mock("${spec}") in ${relative(BB, file)} overrides symbols from ${declFiles.size} files; expected 1`);
        }
        const [declFile] = declFiles;
        enqueue(declFile);
        const target = relativeSpecifier(fileOut, outPathFor(declFile));
        const rewriteLiterals = (inner) => {
          if (ts.isStringLiteral(inner) && inner.text === spec) {
            edits.push({ start: inner.getStart(source), end: inner.end, replacement: `"${target}"` });
          }
          ts.forEachChild(inner, rewriteLiterals);
        };
        rewriteLiterals(node);
        return;
      }
      ts.forEachChild(node, visit);
    };
    visit(source);

    let text = source.text;
    for (const { start, end, replacement } of edits.sort((a, b) => b.start - a.start)) {
      text = text.slice(0, start) + replacement + text.slice(end);
    }
    const leftover = text.match(/["']@bb\/[^"']*["']/);
    if (leftover) {
      throw new Error(`unrewritten ${leftover[0]} left in ${relative(BB, file)}`);
    }
    write(fileOut, text);
  }

  return { files: [...written].sort(), externals: [...externals].sort() };
}

function applyPatch() {
  if (!existsSync(PATCH_FILE)) return;
  const directory = relative(git(REPO_ROOT, "rev-parse", "--show-toplevel"), OUT);
  execFileSync("git", ["apply", `--directory=${directory}`, PATCH_FILE], {
    cwd: REPO_ROOT,
    stdio: "inherit",
  });
  console.log(`applied ${relative(REPO_ROOT, PATCH_FILE)}`);
}

const revision = git(BB, "rev-parse", "HEAD");

if (args["save-patch"]) {
  const manifest = JSON.parse(readFileSync(MANIFEST_FILE, "utf8"));
  if (manifest.bbRevision !== revision) {
    throw new Error(
      `bb checkout is at ${revision} but the vendored copy is from ${manifest.bbRevision}; check out that revision first`,
    );
  }
  const pristine = mkdtempSync(join(tmpdir(), "sawyer-sidebar-"));
  try {
    vendorInto(pristine);
    let patch = "";
    for (const file of manifest.files) {
      try {
        execFileSync(
          "git",
          ["diff", "--no-index", "--src-prefix=a/", "--dst-prefix=b/", join(pristine, file), join(OUT, file)],
          { encoding: "utf8" },
        );
      } catch (error) {
        if (error.status !== 1) throw error;
        patch += error.stdout
          .replaceAll(`a${pristine}/`, "a/")
          .replaceAll(`b${OUT}/`, "b/");
      }
    }
    mkdirSync(dirname(PATCH_FILE), { recursive: true });
    writeFileSync(PATCH_FILE, patch);
    console.log(`wrote ${relative(REPO_ROOT, PATCH_FILE)} (${patch.split("\n").length} lines)`);
  } finally {
    rmSync(pristine, { recursive: true, force: true });
  }
} else {
  if (existsSync(MANIFEST_FILE)) {
    const previous = JSON.parse(readFileSync(MANIFEST_FILE, "utf8"));
    for (const file of previous.files) rmSync(join(OUT, file), { force: true });
  }
  rmSync(join(OUT, "vendor"), { recursive: true, force: true });
  const { files, externals } = vendorInto(OUT);
  const manifest = { bbRevision: revision, source: "plugins/thread-list", files };
  writeFileSync(MANIFEST_FILE, `${JSON.stringify(manifest, null, 2)}\n`);
  console.log(`vendored ${files.length} files from bb ${revision.slice(0, 10)}`);

  const pkgPath = join(OUT, "package.json");
  if (existsSync(pkgPath)) {
    const pkg = JSON.parse(readFileSync(pkgPath, "utf8"));
    const declared = new Set([
      ...Object.keys(pkg.dependencies ?? {}),
      ...Object.keys(pkg.devDependencies ?? {}),
    ]);
    const missing = externals.filter(
      (name) => !declared.has(name) && !name.startsWith("node:"),
    );
    if (missing.length > 0) {
      console.warn(`package.json is missing: ${missing.join(", ")}`);
    }
  }
  applyPatch();
}
